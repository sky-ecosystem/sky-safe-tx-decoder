/**
 * Render one decoded argument for display.
 *
 * Numeric scalars stay `bigint` so the UI's decimals picker remains live, which
 * is the right default where the denomination is not source-backed. Tuples and
 * arrays are flattened to a string, in full — no element is ever elided.
 */
function renderValue(input: AbiParameter, value: unknown): string | bigint | boolean {
  if (typeof value === 'bigint') return value
  if (typeof value === 'boolean') return value
  if (Array.isArray(value)) {
    const components: readonly AbiParameter[] =
      'components' in input ? (input.components ?? []) : []
    return `[${value
      .map((item, i) => String(renderValue(components[i] ?? input, item)))
      .join(', ')}]`
  }
  if (value !== null && typeof value === 'object') {
    const components: readonly AbiParameter[] =
      'components' in input ? (input.components ?? []) : []
    return `{${components
      .map(
        component =>
          `${component.name}: ${String(
            renderValue(component, (value as Record<string, unknown>)[component.name ?? ''])
          )}`
      )
      .join(', ')}}`
  }
  return String(value)
}

/**
 * Decoder for a PAU AdministeredAgent `batchCall`.
 *
 * One instance per AdministeredAgent address. The frozen dispatch tables are
 * shared: a batch may target any Controller, and the table is selected by the
 * Controller address in the calldata, not by which agent forwarded the call.
 */
export class PAUAdministeredAgentDecoder implements CustomDecoder {
  readonly contractAddress: Address
  readonly contractName: string
  readonly network: string

  private readonly tables: readonly PauControllerTable[]

  constructor(
    agent: PauAdministeredAgent,
    tables: readonly PauControllerTable[] = PAU_DISPATCH_TABLES
  ) {
    this.contractAddress = agent.address
    this.contractName = agent.label
    this.network = agent.network
    this.tables = tables
  }

  canDecode(to: Address, data: Hex): boolean {
    const selector = data.slice(0, 10).toLowerCase()
    return (
      to.toLowerCase() === this.contractAddress.toLowerCase() &&
      (selector === PAU_BATCH_CALL_SELECTOR || selector === PAU_CALL_SELECTOR)
    )
  }

  decode(data: Hex): DecodedTransactionData {
    const { functionName, args } = decodeFunctionData({
      abi: ADMINISTERED_AGENT_ABI,
      data,
    })

    const decodedArgs = (args ?? []) as readonly unknown[]

    // Re-encode and byte-compare the outer call. viem's decoder ignores bytes
    // appended past the end of the encoded arguments, so without this check a
    // transaction carrying extra trailing calldata would render as a clean,
    // ordinary batch.
    const reencode = checkReencode(ADMINISTERED_AGENT_ABI, functionName, decodedArgs, data)

    let nested: DecodedFunction[]
    let main: DecodedFunction

    if (functionName === 'call') {
      // A batch of one. The ETH value is msg.value, which the calldata does not
      // carry, so it is passed as null rather than as a guessed zero.
      const [target, call] = decodedArgs as [Address, Hex]
      nested = [this.decodeControllerCall(target, call, null, 0, 1)]
      main = this.describeCall(target, nested)
    } else {
      const [targets, calls, values] = decodedArgs as [
        readonly Address[],
        readonly Hex[],
        readonly bigint[],
      ]
      nested = targets.map((target, i) =>
        this.decodeControllerCall(target, calls[i] ?? '0x', values[i] ?? 0n, i, targets.length)
      )
      main = this.describeBatch(targets, calls, values, nested)
    }

    // Anything a nested call flagged is lifted onto the batch, because the
    // nested-call cards in the UI render name, signature, explanation and
    // parameters but not their own warning list.
    const lifted = nested.flatMap(call => call.warnings ?? [])
    if (lifted.length > 0) main.warnings = [...(main.warnings ?? []), ...lifted]
    if (nested.some(call => call.riskLevel === 'high')) main.riskLevel = 'high'

    // A nested re-encode mismatch means the displayed parameters are not the
    // bytes being signed, which is the same category as an outer mismatch.
    const hardFailures = nested.flatMap(call => call.warnings ?? []).filter(isHardFailure)

    if (reencode.status === 'trailing') {
      // Trailing bytes leave the decoded parameters correct, so this is a
      // warning about bytes the display does not cover, not a reason to
      // distrust the display. It stays out of generalWarnings, which the UI
      // renders as "decoder verification failed". See spbeam.ts.
      main.warnings = [...(main.warnings ?? []), ...reencode.warnings]
      if (main.riskLevel !== 'high') main.riskLevel = 'medium'
      return {
        main,
        nested,
        isMulticall: true,
        ...(hardFailures.length > 0 ? { generalWarnings: hardFailures } : {}),
      }
    }

    if (reencode.status !== 'exact') {
      main.warnings = [...(main.warnings ?? []), ...reencode.warnings]
      main.riskLevel = 'high'
      return {
        main,
        nested,
        isMulticall: true,
        generalWarnings: [...reencode.warnings, ...hardFailures],
      }
    }

    return {
      main,
      nested,
      isMulticall: true,
      ...(hardFailures.length > 0 ? { generalWarnings: hardFailures } : {}),
    }
  }

  getSupportedFunctions(): string[] {
    return ['batchCall', 'call']
  }

  /**
   * `call(address target, bytes data)`: one forwarded call.
   *
   * Same shape as a batch: no per-call rows here, and the call itself carries
   * its target and calldata. The frozen-table caveat is carried here once, as
   * for a batch.
   */
  private describeCall(target: Address, nested: readonly DecodedFunction[]): DecodedFunction {
    const warnings: string[] = []
    const table = findPauControllerTable(this.tables, target)
    if (table) warnings.push(pauFrozenTableCaveat(table.frozenAtBlock, table.frozenAtDate))

    return {
      name: 'call',
      signature: 'call(address,bytes)',
      parameters: [],
      explanation:
        `Forwards 1 call through the Sky PAU AdministeredAgent ${this.contractAddress}, with ` +
        `the ETH value sent to the agent. The call below shows the function that executes ` +
        `and its arguments.`,
      warnings,
      riskLevel: nested.some(call => call.riskLevel === 'high') ? 'high' : 'medium',
    }
  }

  /**
   * The batch itself.
   *
   * Deliberately holds NO per-call rows. Each call's target, selector, value
   * and calldata belong to that call, and a batch-level list of them made every
   * call appear twice on screen: once as flat rows here, once as a decoded card
   * below. Each nested call now carries its own `target` and `rawCalldata`.
   */
  private describeBatch(
    targets: readonly Address[],
    calls: readonly Hex[],
    values: readonly bigint[],
    nested: readonly DecodedFunction[]
  ): DecodedFunction {
    const parameters: DecodedFunction['parameters'] = [
      { name: 'calls', type: 'uint256', value: BigInt(targets.length) },
    ]

    const lengthsAgree =
      targets.length === calls.length && targets.length === values.length

    const warnings: string[] = []
    if (!lengthsAgree) {
      warnings.push(
        `⚠️ The batch arrays are not the same length: ${targets.length} targets, ` +
          `${calls.length} calldata entries, ${values.length} values. AdministeredAgent ` +
          `requires them to match and reverts otherwise. Verify the raw calldata by hand.`
      )
    }

    const nonZeroValue = values.some(value => value > 0n)
    if (nonZeroValue) {
      warnings.push(
        `⚠️ At least one call in this batch forwards ETH. PAU allocator calls normally ` +
          `forward zero. Confirm every non-zero value below.`
      )
    }

    // The frozen-table caveat, once for the batch rather than once per call.
    // Repeating it under every call buried the decoded arguments, and the web
    // UI drops it entirely because its verification banner covers freshness.
    // One entry per distinct table, because a batch may reach two Controllers.
    const seen = new Set<string>()
    for (const target of targets) {
      const table = findPauControllerTable(this.tables, target)
      if (!table) continue
      const key = `${table.frozenAtBlock}:${table.frozenAtDate}`
      if (seen.has(key)) continue
      seen.add(key)
      warnings.push(pauFrozenTableCaveat(table.frozenAtBlock, table.frozenAtDate))
    }

    return {
      name: 'batchCall',
      signature: 'batchCall(address[],bytes[],uint256[])',
      parameters,
      explanation:
        `Forwards ${targets.length} call${targets.length === 1 ? '' : 's'} through the Sky PAU ` +
        `AdministeredAgent ${this.contractAddress}. Each call below shows the function that ` +
        `executes and its arguments.`,
      warnings,
      riskLevel: nested.some(call => call.riskLevel === 'high') ? 'high' : 'medium',
    }
  }

  /**
   * Decode one inner call to a PAU Controller.
   *
   * Every failure path names the reason precisely, because "undecodable" tells
   * a signer nothing about whether to worry.
   */
  private decodeControllerCall(
    target: Address,
    data: Hex,
    value: bigint | null,
    index: number,
    total: number
  ): DecodedFunction {
    const position = `Call ${index + 1} of ${total}`

    if (data.length < 10) {
      return {
        name: 'call with no selector',
        signature: `${position} — no 4-byte selector`,
        parameters: [],
        target,
        rawCalldata: data,
        explanation:
          `${position} carries no 4-byte selector, so nothing identifies what it calls.\n\n` +
          `  • Target — ${target}\n` +
          valueBullet(value),
        warnings: [
          `⚠️ ${position} carries no 4-byte selector. Target ${target}, calldata ${data}. ` +
            `Verify the raw calldata by hand before signing.`,
        ],
        riskLevel: 'high',
      }
    }

    const callSelector = selectorOf(data)
    const table = findPauControllerTable(this.tables, target)

    if (!table) {
      return {
        name: 'unknown Controller',
        signature: `${position} — ${callSelector} on ${target}`,
        parameters: [],
        target,
        rawCalldata: data,
        explanation:
          `${position} cannot be decoded. This build holds no dispatch table for ` +
          `${target}.\n\n` +
          `  • Target — ${target}\n` +
          `  • Call selector — ${callSelector}\n` +
          valueBullet(value) +
          `\n` +
          `Read getDispatch(${callSelector}) on ${target} and decode against the facet it ` +
          `names before signing.`,
        warnings: [
          `⚠️ ${position} targets ${target}, which is not a Controller this build holds a ` +
            `dispatch table for. The call selector ${callSelector} cannot be resolved to a ` +
            `function. Do not sign a call you cannot name.`,
        ],
        riskLevel: 'high',
      }
    }

    const wire = findPauWire(table, callSelector)

    if (!wire) {
      return {
        name: 'unknown call selector',
        signature: `${position} — ${callSelector} on ${target}`,
        parameters: [],
        target,
        rawCalldata: data,
        explanation:
          `${position} cannot be decoded. Call selector ${callSelector} is not in this ` +
          `build's dispatch table for ${table.label} ${table.controller}, frozen at block ` +
          `${table.frozenAtBlock} (${table.frozenAtDate}). A selector wired after that ` +
          `block is absent from it.\n\n` +
          `  • Controller — ${target}\n` +
          `  • Call selector — ${callSelector}\n` +
          valueBullet(value) +
          `\n` +
          `Read getDispatch(${callSelector}) on ${table.controller} and decode against the ` +
          `facet it names before signing.`,
        warnings: [
          `⚠️ ${position} uses call selector ${callSelector} on Controller ${target}, which ` +
            `is not in this build's frozen dispatch table (frozen at block ` +
            `${table.frozenAtBlock}, ${table.frozenAtDate}). Do not sign a call you cannot ` +
            `name.`,
        ],
        riskLevel: 'high',
      }
    }

    return this.decodeWiredCall(wire, target, data, value, position)
  }

  /**
   * Decode an inner call whose dispatch the frozen table covers.
   *
   * The frozen-at block is NOT stated here. It is the same for every call in a
   * batch, so it is carried once as a batch-level warning — see
   * `pauFrozenTableCaveat`.
   */
  private decodeWiredCall(
    wire: PauWire,
    controller: Address,
    data: Hex,
    value: bigint | null,
    position: string
  ): DecodedFunction {
    // The Controller forwards msg.data[4:] verbatim under the delegate
    // selector. Rebuilding exactly those bytes is what makes the decode — and
    // the re-encode check below — describe what the facet receives.
    const delegateData = `${wire.delegateSelector}${data.slice(10)}` as Hex

    const warnings: string[] = []
    let args: readonly unknown[] = []
    let decodeFailed: string | null = null

    try {
      const decoded = decodeFunctionData({ abi: [wire.abi], data: delegateData })
      args = (decoded.args ?? []) as readonly unknown[]
    } catch (error) {
      decodeFailed = error instanceof Error ? error.message : String(error)
    }

    // The context — Controller, both selectors, facet, integration — is carried
    // by the explanation bullets below, and the parameter rows hold the decoded
    // ARGUMENTS only. Putting both in both places printed every call twice
    // inside its own card.
    const context =
      `  • Controller — ${controller}\n` +
      `  • Call selector (sent) — ${wire.callSelector}\n` +
      `  • Delegate selector (executed) — ${wire.delegateSelector}\n` +
      `  • Facet — ${wire.facet}` +
      (wire.facetName ? ` (${wire.facetName})` : '') +
      `\n` +
      `  • Integration id — ${wire.integrationId}` +
      (wire.integrationLabel ? ` (${wire.integrationLabel})` : '') +
      `\n` +
      valueBullet(value)

    const parameters: DecodedFunction['parameters'] = []

    if (decodeFailed) {
      return {
        name: wire.abi.name,
        signature: wire.signature,
        parameters,
        target: controller,
        rawCalldata: data,
        explanation:
          `${position} resolves to ${wire.signature} on facet ${wire.facet}, but the ` +
          `forwarded arguments could not be decoded against that function: ${decodeFailed}\n\n` +
          context,
        warnings: [
          `⚠️ ${position} could not be decoded against ${wire.signature}: ${decodeFailed}. ` +
            `Verify the raw calldata by hand before signing.`,
        ],
        riskLevel: 'high',
      }
    }

    const key = `${wire.facetName}.${wire.signature}`
    const inputs = wire.abi.inputs ?? []
    // Parameters whose value is a token amount this build cannot scale. Named
    // once, in one line, rather than by repeating the argument list.
    const scaleNotes: string[] = []

    for (let i = 0; i < inputs.length; i++) {
      const input = inputs[i]
      if (!input) continue
      const name = input.name || `arg${i}`
      const raw = args[i]

      if (PAU_MAX_SLIPPAGE_FUNCTIONS.has(key) && i === 1) {
        const reading = describeMaxSlippage(raw as bigint)
        parameters.push({
          name,
          type: input.type,
          value: `${reading.value} — ${reading.meaning}`,
        })
        if (reading.warning) warnings.push(`⚠️ ${position}: ${reading.warning.slice(2).trim()}`)
        continue
      }

      if (typeof raw === 'bigint' && /^uint\d*$/.test(input.type)) {
        const reading = readPauAmount(this.network, wire.facetName, wire.signature, i, raw, args)
        // A bare integer keeps the UI's decimals picker live, which is what a
        // signer needs where the scale is undetermined. A scaled string is only
        // emitted where the facet source pins the denomination.
        parameters.push({
          name,
          type: input.type,
          value: reading.scaled ?? raw,
        })
        if (reading.note) scaleNotes.push(`${name} ${reading.note}`)
        continue
      }

      parameters.push({ name, type: input.type, value: renderValue(input, raw) })
    }

    // Re-encode against the bytes the facet receives. The selector swap is the
    // Controller's own behaviour, so proving the decoded arguments reproduce
    // `delegateData` proves they reproduce the signed calldata past its first
    // four bytes, which are shown separately and in full.
    const reencode = checkReencode([wire.abi], wire.abi.name, args, delegateData)
    if (reencode.status !== 'exact') {
      warnings.push(...reencode.warnings.map(warning => `${position}: ${warning}`))
    }

    const note = PAU_FUNCTION_NOTES[key]

    // setMaxExchangeRate stores one derived rate, not its two arguments. State
    // it in full so a signer can compare it with getMaxExchangeRate.
    const exchangeRate = PAU_MAX_EXCHANGE_RATE_FUNCTIONS.has(key)
      ? describeMaxExchangeRate(args[1] as bigint, args[2] as bigint)
      : null
    if (exchangeRate?.warning) warnings.push(`⚠️ ${position}: ${exchangeRate.warning}`)

    return {
      name: wire.abi.name,
      signature: wire.signature,
      parameters,
      target: controller,
      rawCalldata: data,
      explanation:
        context +
        (note ? `\n${note}\n` : '') +
        (exchangeRate ? `\n${exchangeRate.stored}\n` : '') +
        (scaleNotes.length > 0
          ? `\n${scaleNotes.map(note => `${note}.`).join(' ')}\n`
          : ''),
      warnings,
      riskLevel:
        reencode.status === 'mismatch' || reencode.status === 'unverifiable'
          ? 'high'
          : isStateChanging(wire)
            ? 'medium'
            : 'low',
    }
  }
}

/** Build one decoder per known AdministeredAgent. */
export function createPauAgentDecoders(
  tables: readonly PauControllerTable[] = PAU_DISPATCH_TABLES
): PAUAdministeredAgentDecoder[] {
  return PAU_ADMINISTERED_AGENTS.map(agent => new PAUAdministeredAgentDecoder(agent, tables))
}

/**
 * The ETH bullet for a call's context block.
 *
 * Always present. A batch that forwards value is unusual for PAU, and a signer
 * has to be able to see the zero as easily as the non-zero.
 *
 * `null` is `AdministeredAgent.call`, which forwards `msg.value`. That amount
 * is the value of the call to the agent, shown on the transaction, and is not
 * in this calldata. A number here would be a guess.
 */
function valueBullet(value: bigint | null): string {
  const amount =
    value === null
      ? 'the value sent to the AdministeredAgent, which call forwards in full'
      : `${value.toString()} wei`
  return `  • ETH value — ${amount}\n`
}

/** The full 4-byte selector of a call, or `0x` when there is none. */
function selectorOf(data: Hex): Hex {
  return (data.length >= 10 ? data.slice(0, 10).toLowerCase() : '0x') as Hex
}

function isStateChanging(wire: PauWire): boolean {
  return wire.stateMutability !== 'view' && wire.stateMutability !== 'pure'
}

/** Warnings that mean the display does not describe the signed bytes. */
function isHardFailure(warning: string): boolean {
  return warning.includes('DECODED DATA DOES NOT MATCH RAW CALLDATA')
}
